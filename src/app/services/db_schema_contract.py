IdentityMode = Literal["", "a", "d"]
IndexMethod = Literal["btree", "gin"]
TriggerEnabledMode = Literal["O", "D", "R", "A"]
FunctionVolatility = Literal["i", "s", "v"]
FunctionParallelMode = Literal["u", "r", "s"]
PolicyCommand = Literal["r", "a", "w", "d", "*"]


@dataclass(frozen=True, slots=True)
class ColumnSpec:
    """Column type/default as PostgreSQL renders them; None means no default.

    identity is empty for no identity, a for GENERATED ALWAYS, or d for
    GENERATED BY DEFAULT.
    """

    pg_type: str
    nullable: bool
    default: str | None = None
    identity: IdentityMode = ""


@dataclass(frozen=True, slots=True)
class IndexKeySpec:
    """Ordered key expression/operator class with descending and NULL-ordering flags."""

    definition: str
    operator_class: str
    descending: bool = False
    nulls_first: bool = False


@dataclass(frozen=True, slots=True)
class IndexSpec:
    """Exact non-constraint index structure and readiness flags.

    keys and include_columns preserve order; predicate=None means no
    partial-index predicate. Expressions use PostgreSQL's catalog rendering.
    """

    unique: bool
    method: IndexMethod
    keys: tuple[IndexKeySpec, ...]
    include_columns: tuple[str, ...] = ()
    predicate: str | None = None
    valid: bool = True
    ready: bool = True
    live: bool = True
    nulls_not_distinct: bool = False


@dataclass(frozen=True, slots=True)
class FunctionSpec:
    """Exact function signature, source, configuration, and execution properties.

    volatility is i/s/v (immutable/stable/volatile); parallel is u/r/s
    (unsafe/restricted/safe). Text and configuration order compare exactly.
    """

    identity_arguments: str
    result: str
    language: str
    volatility: FunctionVolatility
    security_definer: bool
    strict: bool
    parallel: FunctionParallelMode
    configuration: tuple[str, ...]
    source: str


@dataclass(frozen=True, slots=True)
class TriggerSpec:
    """Exact trigger catalog properties and SQL definition.

    enabled is O/D/R/A (origin/disabled/replica/always); trigger_type is
    PostgreSQL's tgtype bitmask. Application schema means public.
    """

    enabled: TriggerEnabledMode
    internal: bool
    trigger_type: int
    function_schema_is_application: bool
    function_name: str
    definition: str


@dataclass(frozen=True, slots=True)
class RowSecuritySpec:
    """Exact row-security enable/force flags on an application table."""

    enabled: bool
    forced: bool


@dataclass(frozen=True, slots=True)
class PolicySpec:
    """Exact row policy: command r/a/w/d/* means SELECT/INSERT/UPDATE/DELETE/ALL.

    Roles are sorted names; PUBLIC represents PostgreSQL's zero role OID.
    Absent USING/WITH CHECK expressions remain None.
    """

    command: PolicyCommand
    permissive: bool
    roles: tuple[str, ...]
    using: str | None
    with_check: str | None


@dataclass(frozen=True, slots=True)
class ViewSpec:
    """Exact ordered view columns, definition, options and trusted ownership.

    The owner must match the base catalogue table's owner. Hardened runtime
    validation separately requires that owner to be the migration identity.
    """

    columns: tuple[tuple[str, str], ...]
    definition: str
    options: tuple[str, ...]
    owner_matches_catalogue: bool = True


