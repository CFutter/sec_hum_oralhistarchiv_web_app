"""Exact catalog-value contracts consumed by db_drift; dataclasses do not validate inputs.

Function source strings include SQL comments and are compared exactly.
Their public search blob uses title/access_level, a subset of
PUBLIC_DISCOVERY_FIELDS; the full blob uses only the concatenated
fields shown in its SQL. Editing these string literals changes the
runtime contract and requires a corresponding database migration.
"""

