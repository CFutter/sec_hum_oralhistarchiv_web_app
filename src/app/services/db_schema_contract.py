class IndexKeySpec:
    """Ordered key expression/operator class with descending and NULL-ordering flags."""

    definition: str
    operator_class: str
    descending: bool = False
    nulls_first: bool = False


@dataclass(frozen=True, slots=True)
class IndexSpec:
    """Exact non-constraint index structure and readiness flags.

    keys and include_columns preserve order; predicate=None means no
    partial-index predicate. Expressions use PostgreSQL's catalog rendering.
    """

    unique: bool
    method: IndexMethod
    keys: tuple[IndexKeySpec, ...]
    include_columns: tuple[str, ...] = ()
    predicate: str | None = None
    valid: bool = True
    ready: bool = True
    live: bool = True
    nulls_not_distinct: bool = False


@dataclass(frozen=True, slots=True)
class FunctionSpec:
    """Exact function signature, source, configuration, and execution properties.

    volatility is i/s/v (immutable/stable/volatile); parallel is u/r/s
    (unsafe/restricted/safe). Text and configuration order compare exactly.
    """

    identity_arguments: str
    result: str
    language: str
    volatility: FunctionVolatility
    security_definer: bool
    strict: bool
    parallel: FunctionParallelMode
    configuration: tuple[str, ...]
    source: str


@dataclass(frozen=True, slots=True)
class TriggerSpec:
    """Exact trigger catalog properties and SQL definition.

    enabled is O/D/R/A (origin/disabled/replica/always); trigger_type is
    PostgreSQL's tgtype bitmask. Application schema means public.
    """

    enabled: TriggerEnabledMode
    internal: bool
    trigger_type: int
    function_schema_is_application: bool
    function_name: str
    definition: str


